word = input("Введите слово: ")
k = int(input("Введите k (куда вставить): "))
s = int(input("Введите s (какую букву переносим): "))

if s > k:
    # Разрезаем слово на 4 части и склеиваем в нужном порядке:
    # 1. Всё, что до позиции k: word[:k-1]
    # 2. Буква s: word[s-1]
    # 3. Кусок от k до s-1: word[k-1:s-1]
    # 4. Всё, что после s: word[s:]
    
    result = word[:k-1] + word[s-1] + word[k-1:s-1] + word[s:]
    print(f"Результат: {result}")
else:
    print("Ошибка: по условию s должно быть больше k")